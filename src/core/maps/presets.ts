const spawn = (kind: SpawnKind) => (e: readonly [string, number, number, ...unknown[]]): SpawnPoint => ({
  name: e[0],
  lngLat: [e[1], e[2]],
  kind,
});

/** Catalogue entries up to `maxTier` that lie inside the bounding box. */
function catalogue(bbox: BBox, maxTier: number): SpawnPoint[] {
  const inside = (e: Entry) => e[3] <= maxTier && e[1] > bbox[0] && e[1] < bbox[2] && e[2] > bbox[1] && e[2] < bbox[3];
  return [...NATIONS.filter(inside).map(spawn('nation')), ...ELITE_TRIBES.filter(inside).map(spawn('eliteTribe'))];
}

const nations = (...list: [string, number, number][]): SpawnPoint[] => list.map(spawn('nation'));
const elites = (...list: [string, number, number][]): SpawnPoint[] => list.map(spawn('eliteTribe'));

function preset(
  id: string,
  name: string,
  bbox: BBox,
  zoom: [min: number, max: number],
  width: number,
  spawns: SpawnPoint[],
  randomTribes: number,
  extra: Partial<MapPackDefinition> = {},
): MapPackDefinition {
  return { id, name, bbox, zoom: { min: zoom[0], max: zoom[1] }, grid: { width }, terrain: { type: 'osm' }, spawns, randomTribes, ...extra };
}

